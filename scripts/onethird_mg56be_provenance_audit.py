# The number of rows a regeneration MUST rewrite.  Asserted, not hoped for: a
# regeneration that silently rewrites nothing makes a "+regen" run
# indistinguishable from the mutation-alone run it is being compared against,
# and the comparison is the entire experiment.
REGEN_EXPECTED_ROWS = 8


def regenerate(root):
    """Re-run the mutated row builder over the identity population and commit
    what it now produces, into this tree's copy of the dataset.

    FAILS LOUDLY.  A silent no-op here would report "the mutation is still
    caught under regeneration" while no regeneration happened -- which would be
    a false NEGATIVE against mg-4f9b's central measurement, and this file exists
    to test that measurement rather than to manufacture a disagreement with it."""
    proc = subprocess.run(["/usr/bin/python3", "-c", REGEN_SNIPPET],
                          cwd=root, capture_output=True, text=True,
                          env=dict(os.environ, **PINNED))
    if proc.returncode != 0:
        raise SystemExit(f"REGENERATION FAILED, and a swallowed failure here "
                         f"invalidates every '+regen' row:\n"
                         f"{proc.stderr[-3000:]}")
    names = [ln for ln in proc.stdout.splitlines()
             if ln.startswith("REGENERATED ")]
    rows = names[0].split(" ", 1)[1].split(",") if names else []
    if len(rows) != REGEN_EXPECTED_ROWS:
        raise SystemExit(
            f"REGENERATION rewrote {len(rows)} rows, expected "
            f"{REGEN_EXPECTED_ROWS} ({sorted(rows)}).  The identity population "
            f"has changed, or a name no longer resolves -- either way the "
            f"'+regen' rows would be measuring the wrong thing")
    return {"ok": True, "rows": rows}


def extract(stdout):
    fails, ident, census = [], [], []
    grab = False
    for line in stdout.splitlines():
        if line.startswith("CONTROL FAILURES:"):
            grab = True
            continue
        if grab and line.strip().startswith("- "):
            fails.append(line.strip()[2:])
        if "mismatched:" in line or "fields compared" in line:
            ident.append(line.strip())
        if "CENSUS OVER THE DATASET" in line:
            census.append(line.strip())
    return fails, ident, census


def run_case(case, mutation, regen):
    root = tempfile.mkdtemp(prefix=f"mg56be-{case}-")
    try:
        applied = build_tree(root, mutation)
        rinfo = regenerate(root) if regen else None
        proc = subprocess.run(["/usr/bin/python3", GATE, "--no-sweep"],
                              cwd=root, capture_output=True, text=True,
                              env=dict(os.environ, **PINNED))
        fails, ident, census = extract(proc.stdout)
        return {"case": case, "mutation": mutation, "regenerated": rinfo,
                "applied": applied, "exit": proc.returncode,
                "gate_failures": fails, "identity_lines": ident,
                "census_lines": census,
                "stdout_sha256": hashlib.sha256(
                    proc.stdout.encode()).hexdigest(),
                "stderr_tail": (proc.stderr[-2000:] if proc.returncode > 1
                                else "")}
    finally:
        shutil.rmtree(root, ignore_errors=True)


