# ------------------------------------------------------------- tree building --
def _apply_one(root, key):
    mu = MUTATIONS[key]
    path = os.path.join(root, mu["file"])
    with open(path) as f:
        src = f.read()
    got = src.count(mu["old"])
    if got != mu["count"]:
        raise SystemExit(
            f"{key}: anchor found {got} times in {mu['file']}, expected "
            f"{mu['count']} -- the mutation would be a NO-OP and the run "
            f"would be a lie.  Anchor:\n{mu['old']}")
    with open(path, "w") as f:
        f.write(src.replace(mu["old"], mu["new"]))
    return {"file": mu["file"], "occurrences": got}


def build_tree(root, mutation):
    os.makedirs(os.path.join(root, "scripts"))
    os.makedirs(os.path.join(root, "data"))
    for fn in os.listdir(SCRIPTS):
        if fn.endswith(".py"):
            shutil.copy2(os.path.join(SCRIPTS, fn),
                         os.path.join(root, "scripts", fn))
    shutil.copy2(os.path.join(REPO, "data", DATASET),
                 os.path.join(root, "data", DATASET))
    if mutation is None:
        return []
    mu = MUTATIONS[mutation]
    keys = mu.get("composite") or [mutation]
    return [_apply_one(root, k) for k in keys]


# ------------------------------------------------------------- regeneration --
# THE POINT OF THIS FUNCTION.  It is what an author does: edit a probe, re-run
# it, commit the numbers it now produces.  No adversarial intent is needed and
# none is modelled.  It regenerates ONLY the eight rows the gate's identity
# population reads, which is strictly LESS than a real re-run of mg-8b64's probe
