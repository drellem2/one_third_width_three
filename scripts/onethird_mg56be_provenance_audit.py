def part3_invariants():
    """THE CONSTRUCTIVE REFUTATION.  Does a corpus-independent reference exist
    for `frozen_pair_overlap_with_U`?  Five candidates, measured, at baseline
    and under the two mutations the gate absorbs."""
    sys.path.insert(0, SCRIPTS)
    import onethird_mg2c34_n7_overlap_test as gate
    from onethird_mgb0a6_spectral_killshot_probe import enumerate_both_connected
    from onethird_mg4a86_sector_leakage_and_tempering import one_particle_span
    from onethird_mg4a86_sdquant_overlap import projector_U
    import onethird_mg8b64_L1b_bk_transport_transfer_probe as mg8b64

    print()
    print("=" * 78)
    print("PART 3 -- IS THERE A CORPUS-INDEPENDENT REFERENCE FOR")
    print("          frozen_pair_overlap_with_U?  (mg-4f9b says no)")
    print("=" * 78)

    def uncentred(P, x, y):
        """mg-bd53's C2, as a function rather than a source edit, so the
        invariants can be evaluated on both variants in one process."""
        les = P.linear_extensions()
        f = np.zeros(len(les))
        for r, perm in enumerate(les):
            pos = {e: i for i, e in enumerate(perm)}
            f[r] = 1.0 if pos[x] < pos[y] else 0.0
        f -= 0.0 * f.mean()
        nrm = np.linalg.norm(f)
        return f / nrm if nrm > 0 else f

    def evaluate(P, x, y, indicator):
        les = P.linear_extensions()
        m, n = len(les), P.n
        PU, dim_U = projector_U(P)
        f = indicator(P, x, y)
        ov = float(f @ (PU @ f))
        M = one_particle_span(P)
        # I4's witness: g = pos(y) - pos(x) = sum_a a (e_{y,a} - e_{x,a}) in U
        g = np.zeros(m)
        for a in range(n):
            g += a * (M[:, y * n + a] - M[:, x * n + a])
        g = g - g.mean()
        ng = float(np.linalg.norm(g))
        gh = g / ng if ng > 0 else g
        witness_in_U = float(np.linalg.norm(PU @ gh - gh))
        bessel = float((f @ gh) ** 2)
        coef, *_ = np.linalg.lstsq(M, f, rcond=None)
        lsq = float(np.dot(M @ coef, M @ coef))
        return {
            "overlap": ov, "dim_U": int(dim_U), "num_LE": m,
            "I1_abs_sum_f": float(abs(f.sum())),
            "I2_norm_defect": float(abs(np.linalg.norm(f) - 1.0)),
            "I3_in_range": bool(-1e-12 <= ov <= 1.0 + 1e-12),
            "I4_witness_in_U_defect": witness_in_U,
            "I4_bessel_lower_bound": bessel,
            "I4_bound_holds": bool(bessel <= ov + 1e-9),
            "I4_tightness": (bessel / ov) if ov > 0 else None,
            "I5_lstsq_overlap": lsq,
            "I5_route_defect": float(abs(lsq - ov)),
            "I6_vacuity_margin": float(1.0 - ov),
        }

    TOL = {"I1": 1e-9, "I2": 1e-9, "I4_in_U": 1e-9, "I5": 1e-6,
           "I6_floor": 1e-6}

    def verdicts(e):
        return {
            "I1_centring": e["I1_abs_sum_f"] <= TOL["I1"],
            "I2_normalised": e["I2_norm_defect"] <= TOL["I2"],
            "I3_in_range": e["I3_in_range"],
            "I4_bessel": (e["I4_witness_in_U_defect"] <= TOL["I4_in_U"]
                          and e["I4_bound_holds"]),
            "I5_second_route": e["I5_route_defect"] <= TOL["I5"],
            "I6_not_vacuous": e["I6_vacuity_margin"] > TOL["I6_floor"],
        }

    Ps = enumerate_both_connected(7)
    out = {"tolerances": TOL, "posets": []}
    print()
    print("  BASELINE, and the reference each invariant compares against:")
    print(f"  {'poset':>14} {'overlap':>9} {'I1 |sum f|':>11} "
          f"{'I2 |‖f‖-1|':>11} {'I4 bound':>9} {'tight':>7} "
          f"{'I5 |diff|':>10} {'I6 1-ov':>10}")
    for i in gate.OFF_REGIME:
        name = f"enum-n7-#{i}"
        P = Ps[i]
        pairs = mg8b64.bk_frozen_pair(P)["pairs"]
        fr_min = min((pc for pc in pairs if pc["ratio"] is not None),
                     key=lambda pc: pc["ratio"])
        fr_max = max((pc for pc in pairs if pc["ratio"] is not None),
                     key=lambda pc: pc["ratio"])
        base = evaluate(P, fr_min["x"], fr_min["y"],
                        gate.frozen_pair_indicator)
        c2 = evaluate(P, fr_min["x"], fr_min["y"], uncentred)
        m3 = evaluate(P, fr_max["x"], fr_max["y"],
                      gate.frozen_pair_indicator)
        rec = {"name": name,
               "frozen_pair_min_ratio": [int(fr_min["x"]), int(fr_min["y"])],
               "frozen_pair_max_ratio": [int(fr_max["x"]), int(fr_max["y"])],
               "baseline": base, "baseline_verdicts": verdicts(base),
               "C2_uncentred": c2, "C2_verdicts": verdicts(c2),
               "M3_maxratio_pair": m3, "M3_verdicts": verdicts(m3)}
        out["posets"].append(rec)
        print(f"  {name:>14} {base['overlap']:>9.6f} "
              f"{base['I1_abs_sum_f']:>11.2e} {base['I2_norm_defect']:>11.2e} "
              f"{base['I4_bessel_lower_bound']:>9.6f} "
              f"{base['I4_tightness']:>7.4f} {base['I5_route_defect']:>10.2e} "
              f"{base['I6_vacuity_margin']:>10.2e}")

    print()
    print("  DO THEY FIRE ON WHAT THE GATE ABSORBS?  (False = the invariant "
          "is violated,")
    print("  i.e. the mutation is CAUGHT.  Every reference below is 0, 1 or an "
          "inequality,")
    print("  so REGENERATION CANNOT MOVE IT -- there is no stored number.)")
    print()
    keys = ["I1_centring", "I2_normalised", "I3_in_range", "I4_bessel",
            "I5_second_route", "I6_not_vacuous"]
    print(f"  {'variant':<34} " + " ".join(f"{k.split('_')[0]:>5}" for k in keys)
          + "   CAUGHT BY")
    failures = []
    for rec in out["posets"]:
        for tag, vk in (("baseline", "baseline_verdicts"),
                        ("C2 (uncentred)", "C2_verdicts"),
                        ("M3 (max-ratio pair)", "M3_verdicts")):
            v = rec[vk]
            caught = [k.split("_")[0] for k in keys if not v[k]]
            print(f"  {rec['name'] + '  ' + tag:<34} "
                  + " ".join(f"{'ok' if v[k] else 'FIRE':>5}" for k in keys)
                  + f"   {','.join(caught) if caught else '-- nothing'}")
    print()
    # The audit's own assertions: these are what make this file a control.
    for rec in out["posets"]:
        nm = rec["name"]
        if not all(rec["baseline_verdicts"].values()):
            failures.append(
                f"PART 3: {nm}: an invariant FIRES ON THE UNMUTATED TREE "
                f"({[k for k, v in rec['baseline_verdicts'].items() if not v]})"
                f" -- the invariant is wrong, not the corpus")
        if rec["C2_verdicts"]["I1_centring"]:
            failures.append(
                f"PART 3: {nm}: I1 does NOT fire on C2.  The constructive "
                f"refutation of mg-4f9b's negative rests on it")
        if rec["M3_verdicts"]["I6_not_vacuous"]:
            failures.append(
                f"PART 3: {nm}: I6 does NOT fire on M3 (1 - overlap = "
                f"{rec['M3_maxratio_pair']['I6_vacuity_margin']:.2e}) -- M3 "
                f"under regeneration stays open")
    c2_caught = all(not r["C2_verdicts"]["I1_centring"] for r in out["posets"])
    m3_caught = all(not r["M3_verdicts"]["I6_not_vacuous"]
                    for r in out["posets"])
    print(f"  VERDICT ON mg-4f9b's NEGATIVE ('the gate cannot close this "
          f"class'):")
    print(f"    C2, the open instance mg-bd53 found  -- closed by I1 at 3/3 "
          f"posets: {c2_caught}")
    print(f"    M3 under regeneration                -- closed by I6 at 3/3 "
          f"posets: {m3_caught}")
    print(f"    Both references are corpus-independent, so both survive "
          f"regeneration.")
    print(f"    mg-4f9b's DIAGNOSIS (no comparison against the stored "
          f"reference can close")
    print(f"    the class) is CORRECT.  Its CONCLUSION (therefore the gate "
          f"cannot) does not")
    print(f"    follow: neither invariant is such a comparison.")
    out["refutation"] = {"C2_closed_by_I1": c2_caught,
                         "M3_closed_by_I6": m3_caught}
    return out, failures


